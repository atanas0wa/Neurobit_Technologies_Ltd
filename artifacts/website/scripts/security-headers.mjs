/*
 * Applies security-headers.mjs to the build and to every host's config.
 *
 *   node scripts/security-headers.mjs        after `next build`: CSP <meta> per page,
 *                                             out/.htaccess, then the drift check
 *   node scripts/security-headers.mjs sync   rewrite vercel.json, serve.json and .replit
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { csp, headers, ogImage, serializeCsp } from "../security-headers.mjs";

const root = resolve(import.meta.dirname, "..");
const outDir = join(root, "out");
const replitPath = resolve(root, "../../.replit");
const sync = process.argv[2] === "sync";

const ogHeader = { key: "Content-Type", value: ogImage.contentType };

/* ---------- host configs ---------- */

function vercelJson() {
  const current = JSON.parse(readFileSync(join(root, "vercel.json"), "utf8"));
  const config = {
    ...current,
    headers: [
      { source: "/(.*)", headers },
      { source: ogImage.path, headers: [ogHeader] },
    ],
  };
  return JSON.stringify(config, null, 2) + "\n";
}

function serveJson() {
  const config = {
    headers: [
      { source: "**", headers },
      { source: ogImage.path.slice(1), headers: [ogHeader] },
    ],
  };
  return JSON.stringify(config, null, 2) + "\n";
}

const BEGIN = "# BEGIN security headers: generated from artifacts/website/security-headers.mjs";
const END = "# END security headers";

function replitBlock() {
  const entry = (path, { key, value }) =>
    `[[deployment.responseHeaders]]\npath = ${JSON.stringify(path)}\nname = ${JSON.stringify(key)}\nvalue = ${JSON.stringify(value)}\n`;
  const entries = [...headers.map((h) => entry("/*", h)), entry(ogImage.path, ogHeader)];
  return `${BEGIN}\n# Edit that file, then run: pnpm --filter @workspace/website run headers:sync\n${entries.join("\n")}${END}\n`;
}

function replitToml() {
  const current = readFileSync(replitPath, "utf8");
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start === -1) return current.trimEnd() + "\n\n" + replitBlock();
  return current.slice(0, start) + replitBlock() + current.slice(end + END.length + 1);
}

function htaccess() {
  const quote = (value) => `"${value.replace(/["\\]/g, "\\$&")}"`;
  return [
    "# Generated by scripts/security-headers.mjs from security-headers.mjs. Do not edit.",
    "<IfModule mod_headers.c>",
    ...headers.map(({ key, value }) => `  Header always set ${key} ${quote(value)}`),
    "</IfModule>",
    `<Files "${ogImage.path.slice(1)}">`,
    `  ForceType ${ogImage.contentType}`,
    "</Files>",
    "",
  ].join("\n");
}

const hostConfigs = [
  { path: join(root, "vercel.json"), render: vercelJson },
  { path: join(root, "serve.json"), render: serveJson },
  ...(existsSync(replitPath) ? [{ path: replitPath, render: replitToml }] : []),
];

if (sync) {
  for (const { path, render } of hostConfigs) writeFileSync(path, render());
  console.log(`security headers: wrote ${hostConfigs.map(({ path }) => path.replace(root + "/", "")).join(", ")}`);
  process.exit(0);
}

/* ---------- per-page CSP <meta> ---------- */

const META = /<meta http-equiv="Content-Security-Policy"[^>]*>/;
const INLINE_SCRIPT = /<script(?![^>]*\ssrc=)([^>]*)>([\s\S]*?)<\/script>/g;
const DATA_BLOCK = /\stype="application\/(ld\+)?json"/;

function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.name.endsWith(".html") ? [path] : [];
  });
}

if (!existsSync(outDir)) {
  console.error("security headers: out/ not found; run `next build` first");
  process.exit(1);
}

const pages = htmlFiles(outDir);
for (const file of pages) {
  const html = readFileSync(file, "utf8").replace(META, "");
  const hashes = [...html.matchAll(INLINE_SCRIPT)]
    .filter(([, attributes]) => !DATA_BLOCK.test(attributes))
    .map(([, , body]) => `'sha256-${createHash("sha256").update(body).digest("base64")}'`);
  // frame-ancestors is ignored in <meta>; the header carries it.
  const { "frame-ancestors": _, ...metaPolicy } = csp;
  const policy = serializeCsp({ ...metaPolicy, "script-src": ["'self'", ...new Set(hashes)] });
  const meta = `<meta http-equiv="Content-Security-Policy" content="${policy}"/>`;
  const charset = '<meta charSet="utf-8"/>';
  if (!html.includes(charset)) throw new Error(`${file}: no <meta charSet> to anchor the CSP <meta>`);
  writeFileSync(file, html.replace(charset, charset + meta));
}

writeFileSync(join(outDir, ".htaccess"), htaccess());

const stale = hostConfigs.filter(({ path, render }) => !existsSync(path) || readFileSync(path, "utf8") !== render());
if (stale.length) {
  console.error(
    `security headers: ${stale.map(({ path }) => path.replace(root + "/", "")).join(", ")} out of date.\n` +
      "Run `pnpm --filter @workspace/website run headers:sync` and commit the result.",
  );
  process.exit(1);
}
console.log(`security headers: CSP <meta> on ${pages.length} pages, out/.htaccess written, host configs in sync`);
